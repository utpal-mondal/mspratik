CREATE TABLE IF NOT EXISTS `trip` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `folio_id` BIGINT UNSIGNED NOT NULL,
  `gr_challan_no` VARCHAR(100) NOT NULL,
  `date` DATE NOT NULL,
  `invoice_no` VARCHAR(100) NOT NULL,
  `billing_weighment_client` VARCHAR(20) NULL,
  `billing_weighment_broker` VARCHAR(20) NULL,
  `weight_port` DECIMAL(15,3) NULL,
  `weight_grn` DECIMAL(15,3) NULL,
  `weight_other` DECIMAL(15,3) NULL,
  `product_id` BIGINT UNSIGNED NOT NULL,
  `loading_point_id` BIGINT UNSIGNED NOT NULL,
  `unloading_point_id` BIGINT UNSIGNED NOT NULL,
  `product_condition_on_loading` VARCHAR(30) NOT NULL,
  `vessal_id` BIGINT UNSIGNED NULL,
  `firm_id` BIGINT UNSIGNED NOT NULL,
  `session` VARCHAR(7) NOT NULL,
  `vehicle_id` BIGINT UNSIGNED NULL,
  `vehicle_name_fallback` VARCHAR(100) NULL,
  `wheel` INT NULL,
  `vehicle_type` VARCHAR(30) NULL,
  `broker_id` BIGINT UNSIGNED NOT NULL,
  `upper_limit_condition` VARCHAR(100) NULL,
  `broker_payment_type` VARCHAR(30) NULL,
  `broker_price` DECIMAL(15,2) NULL,
  `fuel_qty` DECIMAL(15,3) NULL,
  `fuel_price` DECIMAL(15,2) NULL,
  `fuel_advance` DECIMAL(15,2) NULL,
  `pump_id` BIGINT UNSIGNED NULL,
  `cash_advance` DECIMAL(15,2) NULL,
  `advance_from_client` DECIMAL(15,2) NULL,
  `transporting_charges` DECIMAL(15,2) NULL,
  `total_advance` DECIMAL(15,2) NULL,
  `client_id` BIGINT UNSIGNED NOT NULL,
  `client_price` DECIMAL(15,2) NULL,
  `client_payment_type` VARCHAR(30) NULL,
  `client_advance` DECIMAL(15,2) NULL,
  `consignor_id` BIGINT UNSIGNED NOT NULL,
  `created_at` DATETIME(3) NOT NULL,
  `updated_at` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_trip_folio_id` (`folio_id`),
  KEY `idx_trip_product_id` (`product_id`),
  KEY `idx_trip_loading_point_id` (`loading_point_id`),
  KEY `idx_trip_unloading_point_id` (`unloading_point_id`),
  KEY `idx_trip_vessal_id` (`vessal_id`),
  KEY `idx_trip_firm_id` (`firm_id`),
  KEY `idx_trip_vehicle_id` (`vehicle_id`),
  KEY `idx_trip_broker_id` (`broker_id`),
  KEY `idx_trip_pump_id` (`pump_id`),
  KEY `idx_trip_client_id` (`client_id`),
  KEY `idx_trip_consignor_id` (`consignor_id`),
  CONSTRAINT `fk_trip_folio` FOREIGN KEY (`folio_id`) REFERENCES `folio` (`id`),
  CONSTRAINT `fk_trip_product` FOREIGN KEY (`product_id`) REFERENCES `products` (`id`),
  CONSTRAINT `fk_trip_loading_point` FOREIGN KEY (`loading_point_id`) REFERENCES `loading_point` (`id`),
  CONSTRAINT `fk_trip_unloading_point` FOREIGN KEY (`unloading_point_id`) REFERENCES `unloading_point` (`id`),
  CONSTRAINT `fk_trip_vessal` FOREIGN KEY (`vessal_id`) REFERENCES `vessals` (`id`),
  CONSTRAINT `fk_trip_firm` FOREIGN KEY (`firm_id`) REFERENCES `firm` (`id`),
  CONSTRAINT `fk_trip_vehicle` FOREIGN KEY (`vehicle_id`) REFERENCES `vehicles` (`id`),
  CONSTRAINT `fk_trip_broker` FOREIGN KEY (`broker_id`) REFERENCES `brokers` (`id`),
  CONSTRAINT `fk_trip_pump` FOREIGN KEY (`pump_id`) REFERENCES `pumps` (`id`),
  CONSTRAINT `fk_trip_client` FOREIGN KEY (`client_id`) REFERENCES `clients` (`id`),
  CONSTRAINT `fk_trip_consignor` FOREIGN KEY (`consignor_id`) REFERENCES `consignor` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
